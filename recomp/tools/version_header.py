#!/usr/bin/env python3
"""Write out/rt_version.h: the game version (VERSION), the update list's address
(update_url.txt) and the key it must be signed with (update_key.pub). Run by build.py
before compiling; rewrites the file only when something changed (no needless rebuilds).
docs/UPDATES.md"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def first_line(name, default=''):
    p = os.path.join(ROOT, name)
    if not os.path.exists(p): return default
    for line in open(p, encoding='utf-8'):
        line = line.strip()
        if line and not line.startswith('#'): return line
    return default


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write():
    ver = first_line('VERSION', '0.0.0')
    url = first_line('update_url.txt')
    key = first_line('update_key.pub').lower()
    discord = first_line('discord_app_id.txt')
    if discord and not discord.isdigit():
        print('discord_app_id.txt: not a number (the Application ID) - Discord presence turned off'); discord = ''
    if key and (len(key) != 64 or any(c not in '0123456789abcdef' for c in key)):
        print('update_key.pub: not a 64-character hex key - updates turned off'); key = ''
    text = ('/* generated by tools/version_header.py - do not edit (VERSION, update_url.txt, update_key.pub, discord_app_id.txt) */\n'
            '#define GAME_VERSION %s\n#define GAME_UPDATE_URL %s\n#define GAME_UPDATE_KEY %s\n#define GAME_DISCORD_ID %s\n' % (c_str(ver), c_str(url), c_str(key), c_str(discord)))
    out = os.path.join(ROOT, 'out', 'rt_version.h')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    if os.path.exists(out) and open(out, encoding='utf-8').read() == text: return ver
    with open(out, 'w', encoding='utf-8') as f: f.write(text)
    return ver


if __name__ == '__main__':
    print('version', write())
