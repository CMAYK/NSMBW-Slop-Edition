#!/usr/bin/env python3
"""Progress of moving the 8-player module (THIRD_PARTY_NOTICES.md, recompiled from its PowerPC
build) to native C in runtime/. Writes NATIVE_PORT.md.

A module function counts as ported when its recompiled name (mod_<game function>, or mfn_<addr>
for the module's own helpers) is listed in runtime/hle_funcs.txt: the recompiler then calls the
hand-written hle_<name>() and keeps the PowerPC version as orig_<name>() for comparison.
"""
import collections, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)


def owner(name):
    """class (or 'free functions') a recompiled module function belongs to"""
    n = name[4:] if name.startswith('mod_') else name
    m = re.search(r'__(\d+)([A-Za-z_]\w*)', n)            # CodeWarrior mangling: name__<len>Class...
    if m:
        ln = int(m.group(1)); cls = m.group(2)[:ln]
        if len(cls) == ln: return cls
    m = re.search(r'__Q(\d)(\d+)(\w+)', n)                 # nested: __Q2<len>NS<len>Class
    if m:
        rest = m.group(2) + m.group(3); parts = []
        for _ in range(int(m.group(1))):
            mm = re.match(r'(\d+)', rest); ln = int(mm.group(1)); rest = rest[len(mm.group(1)):]
            parts.append(rest[:ln]); rest = rest[ln:]
        return '::'.join(parts)
    return '(free functions)'


def main():
    syms = [l.split(' = ')[0] for l in open(os.path.join(ROOT, 'config', 'd_project', 'symbols.txt')) if 'type:function' in l]
    hle = set()
    for l in open(os.path.join(ROOT, 'runtime', 'hle_funcs.txt')):
        l = l.split('#')[0].strip()
        if l: hle.add(l)
    repl = [s for s in syms if s.startswith('mod_')]
    # a hand-written function that still calls the module's version is a wrapper, not a port
    import glob
    rt_src = ''.join(open(f, encoding='utf-8', errors='replace').read() for f in glob.glob(os.path.join(ROOT, 'runtime', '*.c')))
    wrapped = {n for n in hle if ('orig_' + n + '(') in rt_src}
    hle -= wrapped
    # source names (tools/mod_source_names.py): module symbol -> replaced game address -> Class::method
    import json
    srcn = {}
    try:
        names = json.load(open(os.path.join(ROOT, 'linked', 'mod_source_names.json')))
        info = json.load(open(os.path.join(ROOT, 'linked', 'mod.json')))
        text = [x for x in info['sections'] if x['kind'] == 'text'][0]['addr']
        dest2game = {d: g for g, d in json.load(open(os.path.join(ROOT, 'linked', 'mod_patches.json')))['replace']}
        for l in open(os.path.join(ROOT, 'config', 'd_project', 'symbols.txt')):
            m = re.match(r'(\S+) = \.text:0x([0-9A-Fa-f]+);', l)
            if not m: continue
            g = dest2game.get(text + int(m.group(2), 16))
            if g is not None and f'{g:08X}' in names: srcn[m.group(1)] = names[f'{g:08X}']['name']
    except OSError: pass
    own = [s for s in syms if s.startswith('mfn_')]
    groups = collections.defaultdict(list)
    for s in repl: groups[srcn[s].rsplit('::', 1)[0] if '::' in srcn.get(s, '') else owner(s)].append(s)
    label = lambda f: (srcn[f].rsplit('::', 1)[-1] if f in srcn else f[4:])
    done = sum(1 for s in repl + own if s in hle)
    out = ['# Native port of the 8-player code', '',
           'Generated by `tools/native_port_status.py` - do not edit by hand.', '',
           'The 8-player features come from an open-source module (MPL-2.0, see THIRD_PARTY_NOTICES.md). Its PowerPC build is linked',
           'and recompiled together with the game (`tools/link_mod.py`, `mod_patches.py`, `recomp.py`).',
           'They are being moved to native C in `runtime/`, one subsystem at a time: add the recompiled',
           'name to `runtime/hle_funcs.txt`, write `hle_<name>()`, and compare against `orig_<name>()`.',
           'Its source (tag v0.6.5, address in THIRD_PARTY_NOTICES.md) is the reference.', '',
           f'**{done} of {len(repl) + len(own)} module functions native** '
           f'({len(repl)} replace game functions, {len(own)} are the module\'s own helpers). '
           f'Wrapped (hand-written code around the module\'s version, *italic*): {sum(1 for s in repl + own if s in wrapped)}.', '',
           '| Class | Native | Functions |', '|---|---|---|']
    for g in sorted(groups, key=lambda g: (-len(groups[g]), g)):
        fs = groups[g]; d = sum(1 for f in fs if f in hle)
        out.append(f'| `{g}` | {d}/{len(fs)} | ' + ', '.join(('**' + label(f) + '**') if f in hle else ('*' + label(f) + '*') if f in wrapped else label(f) for f in sorted(fs, key=label)) + ' |')
    out += ['', 'Bold = native. Recompiled names (for hle_funcs.txt): see `config/d_project/symbols.txt`;',
            'source names come from `linked/mod_source_names.json` (`tools/mod_source_names.py`).', '',
            '| Recompiled name | Source name | Native |', '|---|---|---|']
    for f in sorted(repl, key=lambda f: srcn.get(f, '~' + f)):
        out.append(f'| `{f}` | {srcn.get(f, "")} | {"yes" if f in hle else "wrapped" if f in wrapped else ""} |')
    open(os.path.join(ROOT, 'NATIVE_PORT.md'), 'w').write('\n'.join(out) + '\n')
    print(f'{done}/{len(repl) + len(own)} native, {len(groups)} classes -> NATIVE_PORT.md')


if __name__ == '__main__':
    main()
